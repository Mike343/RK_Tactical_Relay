"""RK Tactical Companion console application for 64-bit Windows."""
import asyncio
import configparser
import ctypes as C
import logging
from logging.handlers import RotatingFileHandler
import os
from pathlib import Path
import sys
import uuid

ROOT = Path(sys.executable if getattr(sys, "frozen", False) else __file__).resolve().parent
RESOURCES = Path(__file__).resolve().parent
sys.path.insert(0,str(RESOURCES/"vendor"))
from audio import Audio
from client import Client
from sim import Sim

VERSION = "2.0.0"


def read_config():
    ini = configparser.ConfigParser(interpolation=None)
    config_path = ROOT / "companion.ini"
    if not config_path.exists():
        # One-file builds carry defaults internally; keep user settings persistent.
        with config_path.open("xb") as destination:
            destination.write((RESOURCES / "companion.ini").read_bytes())
    ini.read(config_path,encoding="utf-8-sig")
    cfg = dict(ini["companion"])
    if not cfg.get("player_id"):
        id_file = ROOT/"companion_id.txt"
        if not id_file.exists(): id_file.write_text(str(uuid.uuid4()),encoding="ascii")
        cfg["player_id"]=id_file.read_text(encoding="utf-8-sig").strip()
    if not cfg.get("display_name") or cfg["display_name"] == "RK Client":
        name = input("Pilot name: ").strip()
        if not name: raise ValueError("A pilot name is required.")
        cfg["display_name"]=name
        ini["companion"]["display_name"]=name
        with (ROOT/"companion.ini").open("w",encoding="utf8") as f: ini.write(f)
    if not cfg["relay_url"].startswith(("ws://","wss://")): raise ValueError("Set relay_url in companion.ini")
    return cfg


async def main():
    if sys.platform!="win32" or C.sizeof(C.c_void_p)!=8:
        raise RuntimeError("This app requires 64-bit Windows.")
    import msvcrt
    os.chdir(ROOT)
    cfg = read_config()
    handlers = [logging.StreamHandler(sys.stdout)]
    if int(cfg.get("log_level","1")):
        handlers.append(RotatingFileHandler(ROOT/"companion.log",maxBytes=4_000_000,backupCount=1,encoding="utf8"))
    logging.basicConfig(level=logging.INFO,format="%(asctime)s %(message)s",handlers=handlers)
    log = logging.getLogger("RK")
    log.info("RK Tactical Companion %s | pilot %s | relay %s",VERSION,cfg["display_name"],cfg["relay_url"])
    # SimConnect loads the first entry of SimConnect.cfg for config index 0.
    # Keep SimConnect.cfg in the persistent folder beside the executable.
    sim_cfg = ROOT/"SimConnect.cfg"
    marker = "; Generated by RK Open Companion"
    if cfg.get("simconnect_host","").strip():
        if sim_cfg.exists() and not sim_cfg.read_text().startswith(marker):
            raise RuntimeError("A custom SimConnect.cfg already exists in this app folder.")
        host=cfg["simconnect_host"].strip()
        port=int(cfg.get("simconnect_port","500"))
        sim_cfg.write_text(f"{marker}\n[SimConnect]\nProtocol=IPv4\nAddress={host}\nPort={port}\n")
    elif sim_cfg.exists() and sim_cfg.read_text().startswith(marker):
        sim_cfg.unlink()
    dll = C.WinDLL(str(RESOURCES/"SimConnect.dll"))
    try: audio=Audio(RESOURCES,cfg)
    except OSError as e:
        log.warning("Windows audio unavailable: %s",e)
        audio=None
    log.info("Q quits. L tests launch audio. M tests the active warning.")
    quitting=False
    def stop():
        nonlocal quitting
        if msvcrt.kbhit():
            key=msvcrt.getwch().lower()
            if key=="q": quitting=True
            if audio and key=="l": audio.once("launch",audio.launch_gain)
            if audio and key=="m":
                audio.manual=not audio.manual
                audio.loop("active",audio.manual or audio.active,audio.active_gain)
        return quitting
    try:
        while not stop():
            sim=Sim(dll)
            try:
                sim.setup()
                log.info("SimConnect open")
                await Client(sim,cfg,audio).run(stop)
            except (OSError,ConnectionError) as e:
                log.warning("Waiting for simulator: %s",e)
                await asyncio.sleep(2)
            finally: sim.close()
    finally:
        if audio: audio.close()


def check_install():
    import wave
    if sys.platform != "win32" or C.sizeof(C.c_void_p) != 8:
        raise RuntimeError("Requires 64-bit Windows.")
    cfg = configparser.ConfigParser(interpolation=None)
    cfg.read(RESOURCES / "companion.ini", encoding="utf-8-sig")
    if not cfg.get("companion", "relay_url").startswith(("ws://", "wss://")):
        raise ValueError("Missing relay_url in companion.ini")
    if getattr(sys, "frozen", False):
        for name in ("msvcp140.dll", "vcruntime140.dll", "vcruntime140_1.dll"):
            if not (RESOURCES / name).is_file():
                raise RuntimeError("Missing bundled runtime: " + name)
    Sim(C.WinDLL(str(RESOURCES / "SimConnect.dll")))
    for name in ("enemy_missile_launch.wav", "enemy_missile_in_air_loop.wav", "brrrt.wav", "Explosion.wav"):
        with wave.open(str(RESOURCES / "Audio" / name), "rb") as clip:
            if clip.getnframes() == 0:
                raise ValueError("Empty audio file: " + name)
    print("Installation check passed. SimConnect DLL, Python modules, configuration and audio assets loaded.")


if __name__ == "__main__":
    try:
        if "--version" in sys.argv:
            print(VERSION)
        elif "--check-install" in sys.argv:
            check_install()
        else:
            asyncio.run(main())
    except KeyboardInterrupt:
        pass
    except Exception:
        import traceback
        traceback.print_exc()
        if "--check-install" not in sys.argv and sys.stdin.isatty():
            input("Press Enter to close.")
        sys.exit(1)
